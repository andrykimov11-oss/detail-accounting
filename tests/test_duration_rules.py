"""
Тесты правил расчёта длительности (SR-34, SR-34а — SR-34г).

Способ проверки SR-34г из SRS-001 §22 дословно: «Справочник единиц
регистрации против правил расчёта длительности → каждому значению
единицы соответствует своё правило; иных правил нет».
"""
from __future__ import annotations

import pytest

from src.duration_rules import (
    UNIT_CUT_MAP,
    UNIT_DETAIL,
    UNIT_DETAIL_QTY,
    UNIT_ORDER,
    duration_by_order,
    durations_by_cut_map,
    durations_by_detail,
    order_closing_expected,
    rule_for_unit,
)


# ----------------------------------------------------------------------
# SR-34г. Каждой единице — своё правило, иных правил нет
# ----------------------------------------------------------------------
def test_sr34г_каждой_единице_соответствует_правило():
    assert rule_for_unit(UNIT_ORDER) == "SR-34б"
    assert rule_for_unit(UNIT_DETAIL) == "SR-34а"
    assert rule_for_unit(UNIT_DETAIL_QTY) == "SR-34а"
    assert rule_for_unit(UNIT_CUT_MAP) == "SR-34в"


def test_sr34г_иных_правил_нет():
    """Неизвестная единица — отказ, а не молчаливый выбор правила по умолчанию."""
    with pytest.raises(ValueError) as e:
        rule_for_unit("что-нибудь")
    assert "неизвестна" in str(e.value)


def test_sr34г_закрытие_заказа_ожидается_только_при_единице_заказ():
    """
    SR-20а: событие закрытия ставится только на участках с единицей
    «заказ». Вопрос решается по справочнику, а не зашитым списком
    участков: на шаге 5 состав таких участков меняется.
    """
    assert order_closing_expected(UNIT_ORDER) is True
    assert order_closing_expected(UNIT_DETAIL) is False
    assert order_closing_expected(UNIT_CUT_MAP) is False


# ----------------------------------------------------------------------
# SR-34б. Единица «заказ»
# ----------------------------------------------------------------------
def test_sr34б_разность_закрытия_и_открытия():
    d = duration_by_order("2026-09-14T08:00:00", "2026-09-14T09:30:00")
    assert d.minutes == 90.0
    assert d.rule == "SR-34б"


# ----------------------------------------------------------------------
# SR-34а. Единица «деталь»
# ----------------------------------------------------------------------
def test_sr34а_первая_позиция_считается_от_открытия_заказа():
    """
    Ключевая связка всего комплекта: подетальный расчёт БЕРЁТ момент
    из позаказного события SR-20. Именно поэтому позаказный и подетальный
    учёт нельзя развести по разным системам.
    """
    ds = durations_by_detail(
        "2026-09-14T08:00:00",
        ["2026-09-14T08:10:00", "2026-09-14T08:25:00"])
    assert ds[0].minutes == 10.0
    assert "открытия заказа" in ds[0].basis
    assert ds[1].minutes == 15.0
    assert "соседних отметок" in ds[1].basis


def test_sr34а_без_открытия_заказа_первая_позиция_без_длительности():
    """
    Если заказ на участке не открыт, начала отсчёта нет. Придумывать его
    нельзя: это не ошибка расчёта, а отсутствие позаказной отметки,
    и в отчёте оно должно быть названо, а не замаскировано нулём.
    """
    ds = durations_by_detail(None, ["2026-09-14T08:10:00",
                                    "2026-09-14T08:25:00"])
    assert ds[0].minutes == 0.0
    assert "не открыт" in ds[0].basis
    assert ds[1].minutes == 15.0


def test_sr34а_число_длительностей_равно_числу_отметок():
    ds = durations_by_detail("2026-09-14T08:00:00",
                             ["2026-09-14T08:05:00",
                              "2026-09-14T08:12:00",
                              "2026-09-14T08:20:00"])
    assert len(ds) == 3


# ----------------------------------------------------------------------
# SR-34в. Единица «карта раскроя»
# ----------------------------------------------------------------------
def test_sr34в_первая_карта_смены_длительности_не_имеет():
    """
    Предыдущей отметки нет, а момент открытия заказа здесь не годится:
    на раскрое один заказ может занимать часть карты, а одна карта —
    нести несколько заказов.
    """
    ds = durations_by_cut_map(["2026-09-14T08:00:00",
                               "2026-09-14T08:40:00",
                               "2026-09-14T09:10:00"])
    assert len(ds) == 2
    assert ds[0].minutes == 40.0
    assert ds[1].minutes == 30.0


def test_sr34в_одна_карта_за_смену_не_даёт_длительности():
    assert durations_by_cut_map(["2026-09-14T08:00:00"]) == []
