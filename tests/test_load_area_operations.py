def test_операция_без_участка_останавливает_загрузку(tmp_path):
    """
    Молчаливый «прочий участок» дал бы работающую систему с неверной
    выработкой. Поэтому — отказ с поимённым перечнем.
    """
    ф = _файл(tmp_path, [("Раскрой плиты 16мм", "Раскрой", ""),
                         ("Новая операция", "", "")], [])
    м = прочитать(ф)
    assert м.без_участка == ["Новая операция"]
    with pytest.raises(СправочникНеполон) as e:
        загрузить(м, tmp_path / "psr.db")
    assert "Новая операция" in str(e.value)


def test_потерянное_решение_технолога_останавливает_загрузку(tmp_path):
    """
    Решение по спорной операции, не нашедшее своей операции, — не
    мелочь: операция осталась бы с прежним участком, а человек был бы
    уверен, что решил. Это и случилось на живых данных трижды.
    """
    ф = _файл(tmp_path,
              [("Раскрой плиты 16мм", "Раскрой", "")],
              [("Операция, которой нет в справочнике", "Сборка", "")])
    with pytest.raises(РешениеПотеряно) as e:
        прочитать(ф)
    assert "Операция, которой нет" in str(e.value)


def test_исключённые_названы_а_не_отфильтрованы_молча(tmp_path):
    ф = _файл(tmp_path, [("Раскрой плиты 16мм", "Раскрой", ""),
                         ("Услуга Дизайнера", "", "не учитывать")], [])
    м = прочитать(ф)
    assert м.исключено == {"Услуга Дизайнера": "не учитывать"}
    assert "Услуга Дизайнера" not in м.операции


def test_решение_по_спорной_сильнее_графы_сегодня(tmp_path):
    """Разметка выгрузки — данные, решение технолога — решение человека."""
    ф = _файл(tmp_path, [("Упаковка фасадов", "Фрезерование", "")],
              [("Упаковка фасадов", "Склад готовой продукции", "")])
    м = прочитать(ф)
    assert м.операции["Упаковка фасадов"] == "Склад готовой продукции"


def test_спорная_без_решения_грузится_и_объявляется(tmp_path):
    """
    Осознанный размен: без неё не считается ничего, с ней считается с
    погрешностью. Погрешность названа, а не спрятана.
    """
    ф = _файл(tmp_path, [("Пропил широкой кромки", "Раскрой", "")],
              [("Пропил широкой кромки", "необходимо уточнить", "спросить цех")])
    м = прочитать(ф)
    assert м.операции["Пропил широкой кромки"] == "Раскрой"
    assert "Пропил широкой кромки" in м.уточнить


