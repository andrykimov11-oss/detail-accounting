def test_имя_приводится_по_незначащим_отличиям():
    """
    Ровно те три расхождения, что случились на живых данных.
    Тест держит именно их, а не абстрактную «нормализацию».
    """
    пары = [
        ('Рез «под плинтус»', 'Рез "под плинтус"'),
        ('Сверление d 60 (кабель-канал)', 'Сверление d 60 (кабель - канал)'),
        ('Сверление под петли в Алюм. профиле', 'Сверление под петли в Алюм.профиле'),
        ('Приёмка на СГП', 'Приемка на СГП'),
        ('  Упаковка  заказа ', 'Упаковка заказа'),
    ]
    for а, б in пары:
        assert ключ(а) == ключ(б), (а, б)


def test_приведение_не_склеивает_разные_операции():
    """
    Правило приведения обязано быть ровно настолько грубым, насколько
    нужно. Склейка двух разных операций хуже несопоставления: вторая
    молча получила бы участок первой.
    """
    разные = [
        ('Раскрой плиты 16мм', 'Раскрой плиты 10мм'),
        ('Облицовывание кромки 19/0,4', 'Облицовывание кромки 19/0,8'),
        ('Упаковка раскроя', 'Упаковка заказа'),
        ('Сверловка глухих отверстий в торце D5', 'Сверловка глухих отверстий в торце D8'),
    ]
    for а, б in разные:
        assert ключ(а) != ключ(б), (а, б)


