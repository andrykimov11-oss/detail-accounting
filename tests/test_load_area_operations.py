"""
Загрузка справочника «операция → участок» из файла технолога.

ПОЧЕМУ ЭТОТ МОДУЛЬ ВООБЩЕ ПРОВЕРЯЕТСЯ ТАК ПОДРОБНО

    Он переносит в систему решение ЧЕЛОВЕКА — разметку 232 операций по
    шести участкам. Ошибка здесь не падает: она даёт работающую систему
    с неверной выработкой участка, а это худший исход из возможных.

    Три опыта ниже воспроизводят то, что уже случилось на живых данных
    при первом запуске: три решения технолога из тринадцати не нашли
    своих операций, потому что названия в двух листах разошлись
    кавычками, пробелом вокруг дефиса и пробелом после точки. Два из
    трёх решений были содержательными — две операции загрузились бы с
    неверным участком, и никто бы не узнал.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from load_area_operations import (  # noqa: E402
    РешениеПотеряно,
    СправочникНеполон,
    ключ,
    загрузить,
    прочитать,
)


def _файл(tmp_path, операции, спорные):
    """Сделать книгу того же вида, что заполняет технолог."""
    import openpyxl

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Операции и участки"
    ws.append(["№", "Операция", "Участок сегодня", "Участок верный",
               "Событий", "Примечание"])
    for i, (имя, сегодня, верный) in enumerate(операции, 1):
        ws.append([i, имя, сегодня, верный, 0, ""])
    ws2 = wb.create_sheet("Спорные операции")
    ws2.append(["№", "Операция", "По справочнику", "Фактически", "Событий",
                "Доля", "Решение", "Примечание"])
    for i, (имя, решение, прим) in enumerate(спорные, 1):
        ws2.append([i, имя, "", "", 0, 0, решение, прим])
    путь = tmp_path / "справочник.xlsx"
    wb.save(путь)
    return путь


