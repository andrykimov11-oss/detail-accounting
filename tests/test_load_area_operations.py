def test_загрузка_заменяет_справочник_целиком(tmp_path):
    """
    Справочник — единая картина. Операция, исчезнувшая из файла
    технолога, обязана исчезнуть из таблицы: досыпка оставила бы
    отменённую привязку жить, и выработка считалась бы по ней.
    """
    from src.storage import Storage

    db = tmp_path / "psr.db"
    ф1 = _файл(tmp_path, [("Раскрой плиты 16мм", "Раскрой", ""),
                          ("Отменяемая операция", "Раскрой", "")], [])
    загрузить(прочитать(ф1), db)
    st = Storage(str(db))
    assert set(st.get_operations_by_area("raskroy")) == \
        {"Раскрой плиты 16мм", "Отменяемая операция"}
    st.close()

    ф2 = _файл(tmp_path, [("Раскрой плиты 16мм", "Раскрой", "")], [])
    загрузить(прочитать(ф2), db)
    st = Storage(str(db))
    assert set(st.get_operations_by_area("raskroy")) == {"Раскрой плиты 16мм"}
    st.close()


def test_участки_раскладываются_по_своим_кодам(tmp_path):
    from src.storage import Storage

    db = tmp_path / "psr.db"
    ф = _файл(tmp_path, [
        ("Раскрой плиты 16мм", "Раскрой", ""),
        ("Облицовывание кромки 19/0,4", "Кромление", ""),
        ("Сверление под петли (d 35)", "Присадка", ""),
        ("Упаковка заказа", "Склад готовой продукции", ""),
    ], [])
    n = загрузить(прочитать(ф), db)
    assert n == 4
    st = Storage(str(db))
    assert st.get_operations_by_area("kromlenie") == ["Облицовывание кромки 19/0,4"]
    assert st.get_operations_by_area("sklad") == ["Упаковка заказа"]
    st.close()
