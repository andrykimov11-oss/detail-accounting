"""
Правило расчёта длительности выбирается единицей регистрации участка.

ЭТО ТРЕБОВАНИЕ, А НЕ УДОБСТВО
    SR-34г: «Правило расчёта длительности ОПРЕДЕЛЯЕТСЯ ЕДИНИЦЕЙ
    РЕГИСТРАЦИИ участка; на участках с единицей "заказ" существует
    событие закрытия заказа (SR-20а)».

    Правил три, и они не взаимозаменяемы:

    SR-34б  единица «заказ» (кромление, сборка): длительность есть
            разность между закрытием (SR-20а) и открытием (SR-20).
            Отметок окончания по деталям на этих участках нет
            и не требуется.

    SR-34а  единица «деталь» (присадка, фрезерование, склад): длительность
            каждой позиции есть разность соседних отметок окончания
            в пределах смены, участка и заказа. ПЕРВАЯ позиция после
            открытия заказа даёт длительность как разность с моментом
            открытия — то есть подетальный расчёт ОПИРАЕТСЯ на позаказное
            событие SR-20 и без него неполон.

    SR-34в  единица «карта раскроя» (BR-21): длительность есть разность
            соседних отметок окончания карт в пределах смены.

ПОЧЕМУ ОДИН МОДУЛЬ, А НЕ ТРИ
    Соблазн был развести расчёты по модулям регистрации: позаказный
    считает своё, подетальный своё. Но тогда правило «какое правило
    применяется» не живёт нигде, и на шаге 5, когда участки переходят
    по одному и в цехе сосуществуют обе единицы, ответ на вопрос
    «как считать этот участок сегодня» пришлось бы искать в двух местах.

    SR-34а закрывает спор окончательно: подетальный расчёт берёт момент
    открытия заказа из позаказного события. Разделить их нельзя даже
    при желании.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Optional

ISO = "%Y-%m-%dT%H:%M:%S"

# Единицы регистрации участка (GLOSS-001 §2.3).
UNIT_ORDER = "order"          # заказ: кромление, сборка
UNIT_DETAIL = "detail"        # деталь: присадка, фрезерование
UNIT_DETAIL_QTY = "detail_qty"  # деталь с количеством: склад
UNIT_CUT_MAP = "cut_map"      # карта раскроя: раскрой


class UnitNotSet(Exception):
    """Единица регистрации участка не задана — справочник не заполнен."""

    def __init__(self, area_id: str):
        super().__init__(
            f"Для участка «{area_id}» не задана единица регистрации. "
            f"Заполняется технологом, пункт 0.3 шага 0."
        )


def _parse(s: str) -> datetime:
    return datetime.strptime(s[:19], ISO)


@dataclass
class Duration:
    """Длительность работы с указанием, каким правилом получена."""

    minutes: float
    rule: str                 # SR-34а / SR-34б / SR-34в
    unit: str
    basis: str                # чем ограничена: словами, для отчёта

    def __post_init__(self):
        self.minutes = round(self.minutes, 1)


# ----------------------------------------------------------------------
# SR-34б. Единица «заказ»
# ----------------------------------------------------------------------
def duration_by_order(opened_at: str, closed_at: str) -> Duration:
    """
    Разность закрытия и открытия заказа на участке.

    Считается по моментам СОБЫТИЙ, а не отметок: отметка задним числом
    не удлиняет работу.
    """
    minutes = (_parse(closed_at) - _parse(opened_at)).total_seconds() / 60.0
    return Duration(minutes, "SR-34б", UNIT_ORDER,
                    "закрытие минус открытие заказа")


# ----------------------------------------------------------------------
# SR-34а. Единица «деталь»
# ----------------------------------------------------------------------
def durations_by_detail(opened_at: Optional[str],
                        marks: list[str]) -> list[Duration]:
    """
    Длительность каждой позиции — разность соседних отметок окончания.

    marks — моменты окончания в пределах ОДНОЙ смены, участка и заказа,
    упорядоченные по времени. Отбор делает вызывающий код: правило
    говорит «в пределах смены, участка и заказа», и эти границы задаёт
    не расчёт, а данные.

    opened_at — момент открытия заказа (SR-20). Даёт начало отсчёта
    ПЕРВОЙ позиции. Если его нет, первая позиция длительности не имеет:
    придумывать ей начало нельзя, и это не ошибка расчёта, а отсутствие
    позаказной отметки.
    """
    out: list[Duration] = []
    prev = opened_at
    for i, m in enumerate(marks):
        if prev is None:
            # Первая позиция без открытия заказа: длительность неизвестна.
            out.append(Duration(0.0, "SR-34а", UNIT_DETAIL,
                                "начало отсчёта отсутствует: "
                                "заказ на участке не открыт (SR-20)"))
            prev = m
            continue
        minutes = (_parse(m) - _parse(prev)).total_seconds() / 60.0
        basis = ("разность с моментом открытия заказа"
                 if i == 0 else "разность соседних отметок окончания")
        out.append(Duration(minutes, "SR-34а", UNIT_DETAIL, basis))
        prev = m
    return out


# ----------------------------------------------------------------------
# SR-34в. Единица «карта раскроя»
# ----------------------------------------------------------------------
def durations_by_cut_map(marks: list[str]) -> list[Duration]:
    """
    Разность соседних отметок окончания карт в пределах смены.

    Первая карта смены длительности не имеет: предыдущей отметки нет,
    а момент открытия заказа здесь не годится — на раскрое один заказ
    может занимать часть карты, а одна карта нести несколько заказов.
    """
    out: list[Duration] = []
    for i in range(1, len(marks)):
        minutes = (_parse(marks[i]) - _parse(marks[i - 1])).total_seconds() / 60.0
        out.append(Duration(minutes, "SR-34в", UNIT_CUT_MAP,
                            "разность соседних отметок окончания карт"))
    return out


# ----------------------------------------------------------------------
# Выбор правила по единице участка — то самое SR-34г
# ----------------------------------------------------------------------
RULE_BY_UNIT = {
    UNIT_ORDER: "SR-34б",
    UNIT_DETAIL: "SR-34а",
    UNIT_DETAIL_QTY: "SR-34а",
    UNIT_CUT_MAP: "SR-34в",
}


def rule_for_unit(unit: str) -> str:
    """
    Какое правило применяется к участку с этой единицей.

    Иных правил нет: способ проверки SR-34г в SRS §22 звучит «каждому
    значению единицы соответствует своё правило; иных правил нет».
    """
    rule = RULE_BY_UNIT.get(unit)
    if rule is None:
        raise ValueError(
            f"Единица регистрации «{unit}» неизвестна. "
            f"Допустимые: {', '.join(RULE_BY_UNIT)}")
    return rule


def order_closing_expected(unit: str) -> bool:
    """
    Ожидается ли на участке событие закрытия заказа (SR-20а).

    Только на участках с единицей «заказ». Вопрос решается ЗДЕСЬ, по
    справочнику, а не зашитым списком участков в модуле регистрации:
    на шаге 5 состав участков с единицей «заказ» меняется.
    """
    return unit == UNIT_ORDER
