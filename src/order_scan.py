"""
Фиксация по коду с бланка заказа (шаг 1 ПСР).

ЧТО СКАНИРУЕТСЯ

    QR на печатной форме «Заказ клиента» несёт **GUID документа 1С**
    (решение владельца D-229 от 02.10.2026):

        a3f1c0de-4b2e-4d11-9f77-0c2b5a8e1234

    ЭТО ИСПРАВЛЕНИЕ, А НЕ РАСШИРЕНИЕ. Прежняя редакция модуля требовала
    пару «номер документа и дата» и на настоящем бланке отказала бы на
    каждом скане. Допущение прожило три недели и было подтверждено
    двадцатью четырьмя тестами, двенадцатью опытами стенда и пятью
    опытами настройки — потому что стенд сам же эти коды и выдавал в
    том виде, какого ждал разборщик (CF-449). Круг был замкнут:
    генератор согласован с разборщиком, оба — с допущением, допущение
    не проверялось ничем.

    Вывод записан решением и повторяется здесь, потому что место тут:
    **испытательный стенд подтверждает согласованность системы с собой,
    а не с действительностью.** Формат кода, формат выгрузки и имена
    папок приходят извне и проверяются образцом из цеха.

    ОГОВОРКА, КОТОРУЮ НЕЛЬЗЯ УБИРАТЬ, ПОКА ОНА ВЕРНА: **настоящего
    бланка проект по-прежнему не видел.** Про GUID известно со слов
    владельца; как GUID выглядит на бумаге — с дефисами, в фигурных
    скобках, с префиксом — не проверено. Поэтому разбор ниже
    снисходителен к обрамлению и строг к существу.

    ПАРА «НОМЕР + ДАТА» НЕ ОТМЕНЕНА. Она остаётся ключом отдачи статуса
    в 1С (решение D-227: тройка «номер + дата + операция» уникальна) и
    принимается скан-разборщиком по-прежнему — на стендах, в отладке и
    на случай, если на части бланков кода не окажется.

ПОЧЕМУ ЭТО НЕ ТО ЖЕ, ЧТО СКАН БИРКИ
    Бирка несёт код ДЕТАЛИ и появляется только на шаге 4. До него
    единственный машиночитаемый код в цехе — на бумажном бланке заказа,
    и фиксация идёт по нему. Один и тот же оператор на шаге 5 начнёт
    сканировать бирки, но заказ при этом никуда не денется: позаказное
    открытие остаётся началом отсчёта для первой детали (SR-34а).

ЧЕГО ЗДЕСЬ НЕТ
    Поиска по всему потоку. Заказ ищется В ПРЕДЕЛАХ СМЕННОГО ЗАДАНИЯ
    (SR-108): девять-одиннадцать заказов против 12 054. Пока выгрузки
    сменного задания нет (пункт 0.8 шага 0), область поиска задаётся
    вызывающим кодом явным списком — и это видно, а не спрятано.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

# Разделитель на усмотрение исполнителя 1С (SETUP-002 §7а), поэтому
# принимаем любой из вероятных, а не один жёстко заданный.
SEPARATORS = "|;,\t"

# Номер документа 1С: префикс из букв и цифр, дефис, цифры.
# Примеры из выгрузки: ПС00-010109, ЛД00-012594, 0Ч00-003266.
DOC_NUM_RE = re.compile(r"^[A-Za-zА-Яа-я0-9]{2,6}-\d{4,10}$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

# GUID документа 1С — то, что в QR на самом деле (D-229).
#
# Снисходительность к обрамлению намеренна: 1С и выгрузки пишут ссылку
# по-разному — в фигурных скобках, заглавными, без дефисов, с префиксом
# «1c:». Настоящего бланка проект не видел, и отвергнуть верный код
# из-за фигурной скобки было бы ровно той же ошибкой, что уже случилась:
# отказ по форме при верном существе. Шестнадцать байт в шестнадцатеричном
# виде — существо; всё остальное — обрамление.
GUID_RE = re.compile(
    r"^\{?([0-9a-fA-F]{8})-?([0-9a-fA-F]{4})-?([0-9a-fA-F]{4})-?"
    r"([0-9a-fA-F]{4})-?([0-9a-fA-F]{12})\}?$")
GUID_PREFIXES = ("1c:", "1с:", "guid:", "ref:")


def normalize_guid(raw: str) -> Optional[str]:
    """
    Привести GUID к одному виду: строчные, через дефисы, без обрамления.

    Возвращает None, если это не GUID. Нормализация нужна не для
    красоты: один и тот же документ, записанный в QR заглавными, а в
    выгрузке строчными, иначе не сойдётся — и отказ будет выглядеть как
    «заказ не найден», то есть как чужой бланк.
    """
    s = (raw or "").strip()
    for p in GUID_PREFIXES:
        if s.lower().startswith(p):
            s = s[len(p):].strip()
            break
    m = GUID_RE.match(s)
    return "-".join(g.lower() for g in m.groups()) if m else None


class ScanNotRecognized(Exception):
    """Код не разобран: это не бланк заказа."""

    def __init__(self, raw: str, why: str):
        self.raw = raw
        super().__init__(f"Код «{raw}» не распознан как бланк заказа: {why}")


class OrderNotInShiftTask(Exception):
    """
    Заказ распознан, но его нет в сменном задании участка.

    SR-108: выбор идёт только среди заказов сменного задания. Заказ
    прошлого года в него попасть не может, и отказ здесь — не придирка,
    а то, что ловит ошибку раньше цеха.
    """

    def __init__(self, doc_num: str, area_id: str):
        self.doc_num = doc_num
        super().__init__(
            f"Заказ {doc_num} не найден в сменном задании участка "
            f"«{area_id}». Проверьте, тот ли бланк, либо обратитесь "
            f"к начальнику цеха."
        )


@dataclass
class ScannedOrder:
    """
    Что прочитано с бланка.

    Два вида кода, и они не равноправны: GUID — то, что печатает 1С
    сегодня (D-229); пара «номер + дата» — прежняя форма, оставленная
    для стендов, отладки и бланков без кода.
    """

    raw: str
    doc_guid: Optional[str] = None    # GUID документа 1С, приведённый к виду
    doc_num: Optional[str] = None     # «ПС00-010109»
    doc_date: Optional[str] = None    # «2026-08-28»

    @property
    def by_guid(self) -> bool:
        return self.doc_guid is not None

    @property
    def key(self) -> str:
        """
        Ключ операции в 1С — пара «номер + дата» (D-227).

        ВАЖНО: ключ отдачи статуса и код на бланке — РАЗНЫЕ вещи.
        Скан опознаёт заказ, ключ адресует строку маршрута. По GUID
        ключа нет, и выдумывать его нельзя: статус ушёл бы не туда.
        """
        if self.doc_num is None or self.doc_date is None:
            raise ValueError(
                "ключ отдачи статуса по GUID не строится: пара «номер + "
                "дата» берётся из связки заказов, а не из скана (D-227)")
        return f"{self.doc_num}|{self.doc_date}"


def parse_order_code(raw: str) -> ScannedOrder:
    """
    Разобрать код с бланка заказа.

    Отказ подробен намеренно: оператор у станка должен понять из экрана,
    что он отсканировал не то, а не увидеть «ошибка».
    """
    if raw is None or not raw.strip():
        raise ScanNotRecognized(str(raw), "пустой код")

    s = raw.strip()

    # GUID проверяется ПЕРВЫМ: это то, что печатает 1С сегодня (D-229).
    guid = normalize_guid(s)
    if guid is not None:
        return ScannedOrder(raw=s, doc_guid=guid)

    # Прежняя форма «номер + дата»: стенды, отладка, бланки без кода.
    parts = None
    for sep in SEPARATORS:
        if sep in s:
            parts = [p.strip() for p in s.split(sep) if p.strip()]
            break
    if parts is None or len(parts) != 2:
        raise ScanNotRecognized(
            s, "ожидался QR с бланка заказа: GUID документа 1С "
               "либо пара «номер документа и дата»")

    doc_num, doc_date = parts
    if not DOC_NUM_RE.match(doc_num):
        raise ScanNotRecognized(
            s, f"«{doc_num}» не похоже ни на GUID, ни на номер документа 1С")
    if not DATE_RE.match(doc_date):
        raise ScanNotRecognized(
            s, f"«{doc_date}» не похоже на дату в виде ГГГГ-ММ-ДД")

    return ScannedOrder(raw=s, doc_num=doc_num, doc_date=doc_date)


class OrderScanResolver:
    """
    Отсканированный бланк → номер заказа БАЗИС, с которым работает система.

    Связка «документ 1С ↔ заказ БАЗИС» уже построена смежным
    направлением и живёт в order_links. Здесь она только читается:
    заводить вторую связку нельзя, иначе об одном заказе появятся
    две истины.
    """

    def __init__(self, storage):
        self.st = storage

    def resolve(self, raw: str, area_id: str,
                shift_task: Optional[list[int]] = None) -> int:
        """
        Вернуть номер заказа БАЗИС по коду с бланка.

        shift_task — номера заказов сменного задания участка (SR-108).
        Если не задан, поиск идёт по всей связке: так работает до того,
        как появится выгрузка сменного задания (пункт 0.8 шага 0).
        """
        scanned = parse_order_code(raw)
        if scanned.by_guid:
            order_num = self.st.find_order_by_guid(scanned.doc_guid)
            if order_num is None:
                # Отказ назван точно, потому что причин ДВЕ, и они
                # требуют разных действий. Либо бланк чужой — дело
                # оператора. Либо GUID не пришёл в выгрузке 1С — дело
                # программиста 1С, и оператор тут бессилен. Сообщение
                # «заказ не найден» свалило бы оба случая в один, и
                # месяц искали бы не там.
                raise ScanNotRecognized(
                    scanned.raw,
                    "код с бланка не сопоставлен ни с одним заказом. "
                    "Либо бланк не от этого цеха, либо выгрузка из 1С "
                    "пришла без колонки с кодом документа — тогда это "
                    "вопрос к настройке, а не к бланку")
        else:
            order_num = self.st.find_order_by_doc(scanned.doc_num, scanned.doc_date)
            if order_num is None:
                raise ScanNotRecognized(
                    scanned.raw,
                    f"документ {scanned.doc_num} от {scanned.doc_date} "
                    f"не связан ни с одним заказом БАЗИС")

        if shift_task is not None and order_num not in shift_task:
            # В сообщении — то, что оператор видит на бумаге. GUID он
            # глазами не читает, поэтому называется номер заказа.
            raise OrderNotInShiftTask(
                scanned.doc_num or f"№ {order_num}", area_id)

        return order_num
