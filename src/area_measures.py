"""
Натуральные измерители участков (SR-26а — SR-26е).

ЗАЧЕМ
    Выработку участка нельзя мерить числом отметок: отметка на раскрое и
    отметка на сборке — разная работа. Поэтому у каждого участка есть свой
    натуральный измеритель, и выработка считается в нём (BR-42).

ДВА СВОЙСТВА, КОТОРЫЕ ЗДЕСЬ ОБЕСПЕЧИВАЮТСЯ

    SR-26а. У участка РОВНО ОДИН измеритель. Это свойство схемы, а не
    дисциплины: area_id — первичный ключ справочника, второй строки для
    участка физически не существует.

    SR-26б. Значение измерителя вычисляется ИЗ СПЕЦИФИКАЦИИ БАЗИС до
    начала работы и не зависит от отметок оператора. Поэтому все функции
    ниже читают `details` — плановый состав заказа — и не смотрят ни в
    scan_events, ни в facts. Оператор не может изменить выработку тем,
    как он отмечает.

ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ
    Подсветка отклонения (шаг 2) сравнивает выработку со скользящей
    медианой участка. Если измеритель зависел бы от отметок, участок мог
    бы влиять на собственный норматив способом отметки. Требование SR-26б
    закрывает это не проверкой, а источником данных.

ЧЕГО ЗДЕСЬ НЕТ
    Справочник НЕ заполняется кодом. Его заполняет технолог (пункт 0.3
    шага 0, лист `SETUP-001`). Здесь — только хранение, правило «ровно
    один» и вычисление значения. Значения по умолчанию не проставляются
    намеренно: измеритель участка есть решение предприятия, а не догадка
    системы.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Optional


# Коды измерителей. Строка, а не Enum: справочник заполняет технолог,
# и набор может пополниться без правки кода.
#
# РЕШЕНИЕ D-210 (19.09.2026) переопределило четыре измерителя из шести.
# Общее правило, которое владелец сформулировал за всеми четырьмя:
# работа участка меряется тем, что через него ФИЗИЧЕСКИ проходит, а не
# тем, сколько там различных позиций спецификации. Деталь подаётся в
# станок по одной независимо от того, уникальна она или двадцатая такая
# же, — значит считать надо экземпляры, а не уникальные.
SHEETS = "sheets"                 # листы — раскрой
EDGE_METERS = "edge_meters"       # погонные метры кромки — кромление
DETAIL_ITEMS = "detail_items"     # экземпляры деталей — сборка, склад
MILLED_ITEMS = "milled_items"     # экземпляры на фрезерование
DRILLED_ITEMS = "drilled_items"   # экземпляры на присадку

# Отменены решением D-210. Оставлены только чтобы старая запись в
# справочнике не падала с невнятной ошибкой: см. RETIRED_MEASURES ниже.
UNIQUE_DETAILS = "unique_details"  # было: фрезерование, склад
PRODUCTS = "products"              # было: сборка («Обозначение изделия»)

MEASURE_NAMES = {
    SHEETS: "листы",
    EDGE_METERS: "пог. м кромки",
    DETAIL_ITEMS: "детали",
    MILLED_ITEMS: "детали на фрезерование",
    DRILLED_ITEMS: "детали на присадку",
}

RETIRED_MEASURES = {
    UNIQUE_DETAILS: "отменён D-210: считать надо экземпляры, а не "
                    "уникальные позиции — деталь подаётся по одной",
    PRODUCTS: "отменён D-210: измеритель сборки — детали, а не изделия. "
              "Поле «Обозначение изделия» пусто во всей выгрузке (CF-419), "
              "и тумба из 6 деталей нормируется иначе, чем кухня из 200",
    "unique_milled": "отменён D-210: заменён на milled_items",
}


class MeasureNotSet(Exception):
    """
    Для участка не задан измеритель.

    Это не сбой программы, а незаполненный справочник: пункт 0.3 шага 0.
    Исключение названо отдельно, чтобы вызывающий код мог отличить
    «технолог ещё не заполнил» от «в данных ошибка».
    """

    def __init__(self, area_id: str):
        self.area_id = area_id
        super().__init__(
            f"Для участка «{area_id}» не задан натуральный измеритель "
            f"(SR-26а). Заполняется технологом, пункт 0.3 шага 0."
        )


class MeasureNotComputable(Exception):
    """Измеритель задан, но вычислить его по спецификации нечем."""

    def __init__(self, area_id: str, measure_code: str, why: str):
        super().__init__(
            f"Измеритель «{measure_code}» участка «{area_id}» "
            f"не вычисляется: {why}"
        )


@dataclass
class AreaMeasure:
    area_id: str
    measure_code: str
    measure_name: str


# ----------------------------------------------------------------------
# Вычисление по спецификации (SR-26б): читаем details, не отметки
# ----------------------------------------------------------------------
def _sheets(rows) -> float:
    """
    Раскрой: число листов.

    КЛЮЧ — ПАРА (файл спецификации, номер плиты), А НЕ НОМЕР ПЛИТЫ.
        Заказ режется из нескольких материалов, и на каждый материал
        БАЗИС выгружает свой .xbir, где нумерация плит начинается
        заново с единицы. Плита №1 в файле «Кроношпан» и плита №1 в
        файле «Орех Кария» — два разных физических листа.

        Первая редакция считала различные номера плиты по всему заказу
        и потому складывала эти листы в один. Проверка на выгрузке (238
        файлов, 68 заказов) показала занижение более чем вдвое: 194
        листа вместо 404. Из 57 заказов, выгруженных несколькими
        файлами, занижены были ВСЕ 57 (CF-424).

        «Номер карты» той же беде подвержен — он тоже нумеруется внутри
        файла: пара (карта, плита) даёт те же 194.
    """
    plates = {(r["source_file"], r["plate_no"])
              for r in rows if r["plate_no"]}
    if not plates:
        raise MeasureNotComputable(
            "raskroy", SHEETS,
            "в спецификации нет номеров плиты; вероятно, .xbir разобран "
            "версией парсера до того, как поле стало сохраняться")
    return float(len(plates))


def _edge_meters(rows) -> float:
    """
    Кромление: погонные метры кромки заказа.

    Длина кромки детали умножается на плановое количество экземпляров:
    оклеивается каждый экземпляр, а не позиция спецификации.
    Величина хранится в миллиметрах, приводится к метрам.
    """
    total_mm = sum((r["edge_total_len"] or 0) * (r["qty"] or 0) for r in rows)
    return round(total_mm / 1000.0, 2)


def _detail_items(rows) -> float:
    """
    Сборка и склад готовой продукции: экземпляры деталей заказа
    (SR-26д, SR-26е в редакции D-210).

    Считаются ЭКЗЕМПЛЯРЫ, а не позиции спецификации: двадцать одинаковых
    полок собираются и укладываются двадцать раз, а не один.

    На сборке это заодно заменило прежний измеритель «изделие». Довод
    владельца: тумбу из шести деталей и кухню из двухсот нельзя
    нормировать одинаково, а «изделие» их уравнивало — при том что поле
    «Обозначение изделия» в выгрузке пусто всегда (CF-419).
    """
    return float(sum((r["qty"] or 0) for r in rows))


# ---------------------------------------------------------------------------
# Измерители, которые СЕГОДНЯ ЗАНИЖАЮТ, и это названо, а не спрятано
# ---------------------------------------------------------------------------
#
# Решение владельца D-236 от 03.10.2026: признак прохождения участка
# берётся НЕ из поля спецификации. Проверено на данных:
#
#     по данным 1С     фрезерование 19,0 % заказов, присадка 27,9 %
#     по полю .xbir    фрезерование   12 %,         присадка   19 %
#
# То есть поле неполно примерно в полтора раза. Технолог назвал причину:
# признак фрезерования — наличие операции фрезерования В КОММЕНТАРИИ к
# детали, а не поле пазов.
#
# ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ, И ПОЧЕМУ ИМЕННО ТАК.
#
#   Не отказывается считать. Значение по полю — не мусор, а НИЖНЯЯ
#   ГРАНИЦА: деталь с пазами фрезерование проходит наверняка. Отказ
#   погасил бы экран оператора на двух участках из шести без нужды.
#
#   Не подменяет правило догадкой. Формат комментария проекту неизвестен
#   (вопрос OQ-130), и «ищем слово „фрезеровка“» — именно догадка. На
#   догадке о внешнем формате проект уже дважды построил разборщик кода
#   с бланка и дважды ошибся (CF-449, D-232).
#
#   Не позволяет считать по этому значению НОРМАТИВ. Удельный норматив
#   шага 2 делит время на выработку: заниженная выработка завысит время
#   на единицу, и подсветка отклонений сработает не там. Поэтому
#   `assert_usable_for_norms` отказывает явно, а не вычисляет тихо.
ЗАНИЖАЮЩИЕ: dict[str, str] = {
    MILLED_ITEMS:
        "отбор по полю пазов даёт 12 % заказов против 19,0 % по данным 1С "
        "(D-236). Признак — в комментарии к детали, его формат выясняется "
        "вопросом OQ-130. Значение считать нижней границей",
    DRILLED_ITEMS:
        "отбор по полю сверления даёт 19 % заказов против 27,9 % по данным "
        "1С (D-236). Признак уточняется вопросом OQ-130. Значение считать "
        "нижней границей",
}


class ИзмерительЗанижает(Exception):
    """Величина годна для показа, но не годна для норматива."""

    def __init__(self, measure: str, почему: str):
        super().__init__(
            f"измеритель «{MEASURE_NAMES.get(measure, measure)}» сегодня "
            f"занижает выработку и для расчёта норматива не годится: "
            f"{почему}")
        self.measure = measure


def assert_usable_for_norms(measure: str) -> None:
    """
    Страж шага 2: годится ли измеритель для удельного норматива.

    Вызывается ПЕРЕД расчётом норматива, а не после. Норматив, посчитанный
    по заниженной выработке, выглядит обычным числом — ошибку в нём
    обнаружить нечем.
    """
    if measure in ЗАНИЖАЮЩИЕ:
        raise ИзмерительЗанижает(measure, ЗАНИЖАЮЩИЕ[measure])


def _milled_items(rows) -> float:
    """
    Фрезерование: экземпляры деталей, ПРОХОДЯЩИХ фрезерование
    (SR-26г в редакции D-210, с оговоркой D-236).

    Два условия, и они разные:
      — отбор по признаку остаётся: не весь заказ идёт на участок,
        и считать весь значило бы завысить выработку в разы;
      — уникальность снята: деталь подаётся в станок по одной, и
        двадцатая такая же требует той же подачи, что первая.

    СЕГОДНЯ ЭТО НИЖНЯЯ ГРАНИЦА — см. ЗАНИЖАЮЩИЕ выше.
    """
    return float(sum((r["qty"] or 0)
                     for r in rows if (r["grooves"] or 0) > 0))


def _drilled_items(rows) -> float:
    """
    Присадка: экземпляры деталей со сверлением (SR-26и в редакции D-210,
    с оговоркой D-236).

    Поведение по экземплярам не изменилось. Изменилось знание о полноте
    отбора: поле сверления охватывает не всех, кого охватывает 1С.

    СЕГОДНЯ ЭТО НИЖНЯЯ ГРАНИЦА — см. ЗАНИЖАЮЩИЕ выше.
    """
    return float(sum((r["qty"] or 0)
                     for r in rows if (r["drill_total"] or 0) > 0))


CALCULATORS: dict[str, Callable] = {
    SHEETS: _sheets,
    EDGE_METERS: _edge_meters,
    DETAIL_ITEMS: _detail_items,
    MILLED_ITEMS: _milled_items,
    DRILLED_ITEMS: _drilled_items,
}


class AreaMeasures:
    """Справочник измерителей участков и вычисление значений по заказу."""

    def __init__(self, storage):
        self.st = storage

    # -- справочник (SR-26а) -------------------------------------------
    def set_measure(self, area_id: str, measure_code: str,
                    measure_name: str = "") -> AreaMeasure:
        """
        Задать измеритель участка. Повторный вызов ЗАМЕНЯЕТ прежний,
        а не добавляет второй: у участка ровно один измеритель.
        """
        name = measure_name or MEASURE_NAMES.get(measure_code, measure_code)
        self.st.set_area_measure(area_id, measure_code, name)
        return AreaMeasure(area_id, measure_code, name)

    def get_measure(self, area_id: str) -> AreaMeasure:
        row = self.st.get_area_measure(area_id)
        if row is None:
            raise MeasureNotSet(area_id)
        return AreaMeasure(row["area_id"], row["measure_code"],
                           row["measure_name"])

    def all_measures(self) -> list[AreaMeasure]:
        return [AreaMeasure(r["area_id"], r["measure_code"], r["measure_name"])
                for r in self.st.get_area_measures()]

    def areas_without_measure(self, area_ids: list[str]) -> list[str]:
        """
        Участки, для которых технолог ещё не задал измеритель.

        Нужно для признака завершения пункта 0.3: «все шесть участков
        заполнены». Проверяется списком, а не на глаз.
        """
        have = {m.area_id for m in self.all_measures()}
        return [a for a in area_ids if a not in have]

    # -- вычисление (SR-26б) -------------------------------------------
    def value_for_order(self, area_id: str, order_num: int) -> float:
        """
        Значение измерителя участка для заказа — из спецификации БАЗИС.

        Ни одна отметка оператора на результат не влияет: читается только
        плановый состав заказа.
        """
        m = self.get_measure(area_id)
        calc = CALCULATORS.get(m.measure_code)
        if calc is None:
            # Отменённый измеритель отличаем от неизвестного: иначе
            # технолог, у которого в справочнике осталась прежняя
            # запись, получит «правило не задано» и пойдёт искать
            # дефект в коде вместо того, чтобы перезаполнить строку.
            why = RETIRED_MEASURES.get(
                m.measure_code,
                "правило вычисления для этого измерителя не задано")
            raise MeasureNotComputable(area_id, m.measure_code, why)
        rows = self.st.get_details_by_order(order_num)
        if not rows:
            raise MeasureNotComputable(
                area_id, m.measure_code,
                f"спецификация заказа {order_num} не загружена")
        return calc(rows)

    def is_lower_bound(self, area_id: str) -> bool:
        """
        Значение измерителя — нижняя граница, а не точная величина?

        Нужно экрану и отчёту: число, про которое известно, что оно
        занижено, обязано показываться как «не менее N». Иначе человек
        сравнит его с планом и примет решение по неполным данным,
        не узнав, что данные неполны.
        """
        return self.get_measure(area_id).measure_code in ЗАНИЖАЮЩИЕ

    def lower_bound_reason(self, area_id: str) -> str:
        """Чем именно занижено — для показа человеку, а не в журнал."""
        return ЗАНИЖАЮЩИЕ.get(self.get_measure(area_id).measure_code, "")
