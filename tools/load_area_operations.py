#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Загрузка справочника «операция 1С → участок» из файла технолога.

ЗАЧЕМ ЭТОТ ЗАГРУЗЧИК

    Требование SR-83: привязка операции к участку — НАСТРАИВАЕМЫЕ ДАННЫЕ,
    а не правило в коде. До сих пор она жила двенадцатью захардкоженными
    строками `operation_mapping.OPERATION_RULES`, и отвечать за неё
    приходилось программисту вместо технолога.

    Пункт 0.3 шага 0 закрыт технологом 03.10.2026: 232 операции
    размечены по шести участкам в файле `Справочники_шага_0_технолог.xlsx`.
    Этот модуль переносит разметку в таблицу `area_operations` — и больше
    ничего не делает.

ЧТО МОДУЛЬ ДЕЛАЕТ НАМЕРЕННО ГРОМКО, А НЕ ТИХО

    1. **Операции без участка — отказ, а не «прочее».** Операция, которой
       технолог не назначил участок, не попадает никуда и останавливает
       загрузку с поимённым перечнем. Молчаливый «прочий участок» дал бы
       работающую систему с неверной выработкой — худший из исходов.

    2. **Исключённые операции названы поимённо.** «Услуга дизайнера»,
       «Экспедиторские услуги», «Кромка в отмотку» — не операции цеха.
       Они перечислены в отчёте, а не отфильтрованы незаметно: иначе
       через месяц никто не вспомнит, почему операций 227, а не 230.

    3. **Спорные операции, помеченные «необходимо уточнить», грузятся по
       нынешнему участку и ОБЪЯВЛЯЮТСЯ.** Это осознанный размен: без них
       не считается ничего, с ними считается с известной погрешностью.
       Погрешность названа, а не спрятана.

Запуск:
    python3 tools/load_area_operations.py --xlsx "…/Справочники_шага_0_технолог.xlsx" \\
                                          --db ./teststand/psr.db
    python3 tools/load_area_operations.py --xlsx … --db … --dry-run
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

# Шесть участков первого этапа. Перечень ЯВНЫЙ: значение в графе
# «участок верный», не совпавшее ни с одним, — это не участок, а
# указание технолога («не учитывать»), и путать их нельзя.
УЧАСТКИ = {
    "Раскрой": "raskroy",
    "Кромление": "kromlenie",
    "Присадка": "prisadka",
    "Фрезерование": "frezerovanie",
    "Сборка": "sborka",
    "Склад готовой продукции": "sklad",
}

ЛИСТ_ОПЕРАЦИЙ = "Операции и участки"
ЛИСТ_СПОРНЫХ = "Спорные операции"


def ключ(имя: str) -> str:
    """
    Имя операции, приведённое к виду, по которому сравнивают.

    ЗАЧЕМ ЭТО НУЖНО, И ЭТО НЕ УКРАШЕНИЕ. Лист спорных операций заполнялся
    из разбора `ASIS-004`, где названия переписаны человеком, а лист
    операций — прямо из выгрузки 1С. Три названия из тринадцати разошлись
    незначащими отличиями:

        «Рез «под плинтус»»                   против  «Рез "под плинтус"»
        «Сверление d 60 (кабель-канал)»       против  «… (кабель - канал)»
        «Сверление под петли в Алюм. профиле» против  «… в Алюм.профиле»

    Без приведения три решения технолога не нашли бы своих операций и
    пропали бы МОЛЧА — две операции загрузились бы с неверным участком.
    Кавычки, пробелы и регистр значения не несут; всё остальное несёт.
    """
    s = (имя or "").strip().lower()
    for кавычка in ('«', '»', '"', "'", '„', '“', '”'):
        s = s.replace(кавычка, '"')
    s = s.replace('ё', 'е')
    # Точка приводится к пробелу: «Алюм.профиле» и «Алюм. профиле» —
    # одна операция. В названиях операций дробные числа пишутся через
    # ЗАПЯТУЮ («19/0,4», «D 3,5»), поэтому точка разделителем не служит
    # нигде, кроме сокращений, и приведение безопасно. Проверено на всех
    # 232 названиях: приведение не склеило ни одной пары разных операций
    # — это сверяется тестом, а не утверждается.
    for знак in ('"', '-', '.'):
        s = s.replace(знак, ' ')
    return " ".join(s.split())


class РешениеПотеряно(Exception):
    """Решение по спорной операции не нашло своей операции в справочнике."""

    def __init__(self, потеряны: dict):
        super().__init__(
            "решение технолога по этим операциям не к чему применить — "
            "в справочнике нет операции с таким названием. Молча "
            "пропустить нельзя: решение человека потерялось бы, а "
            "операция осталась бы с прежним участком:\n  " +
            "\n  ".join(f"«{k}» → {v}" for k, v in потеряны.items()))
        self.потеряны = потеряны


class СправочникНеполон(Exception):
    """Операции без участка: загружать нельзя."""

    def __init__(self, операции: list[str]):
        super().__init__(
            "у этих операций не назначен участок, и подставить его "
            "модуль не вправе — выработка участка стала бы неверной "
            "молча:\n  " + "\n  ".join(операции))
        self.операции = операции


@dataclass
class Разметка:
    """Что прочитано из файла технолога."""
    операции: dict = field(default_factory=dict)      # название → участок
    исключено: dict = field(default_factory=dict)     # название → почему
    без_участка: list = field(default_factory=list)
    уточнить: dict = field(default_factory=dict)      # название → примечание

    @property
    def готово(self) -> int:
        return len(self.операции)


def прочитать(xlsx: Path) -> Разметка:
    import openpyxl

    wb = openpyxl.load_workbook(xlsx, data_only=True)
    for лист in (ЛИСТ_ОПЕРАЦИЙ, ЛИСТ_СПОРНЫХ):
        if лист not in wb.sheetnames:
            raise ValueError(f"в файле нет листа «{лист}»: {xlsx}")

    # Решения по спорным операциям читаются ПЕРВЫМИ: они сильнее графы
    # «участок сегодня», потому что приняты человеком, а не выгрузкой.
    спор: dict[str, tuple[str, str]] = {}
    спор_имена: dict[str, str] = {}      # ключ → как написано у технолога
    for r in wb[ЛИСТ_СПОРНЫХ].iter_rows(min_row=2, values_only=True):
        if not isinstance(r[0], (int, float)) or not r[1]:
            continue
        спор_имена[ключ(str(r[1]))] = str(r[1]).strip()
        спор[ключ(str(r[1]))] = (
            str(r[6]).strip() if len(r) > 6 and r[6] else "",
            str(r[7]).strip() if len(r) > 7 and r[7] else "")

    м = Разметка()
    применено: set[str] = set()
    for r in wb[ЛИСТ_ОПЕРАЦИЙ].iter_rows(min_row=2, values_only=True):
        # Строка требования опознаётся по номеру в первой ячейке: ниже
        # таблицы идут пояснения, и они не операции.
        if not isinstance(r[0], (int, float)) or not r[1]:
            continue
        имя = str(r[1]).strip()
        сегодня = str(r[2]).strip() if r[2] else ""
        верный = str(r[3]).strip() if r[3] else ""

        if верный and верный not in УЧАСТКИ:
            # В графу «участок верный» написан не участок — значит
            # указание, а не разметка.
            м.исключено[имя] = верный
            continue

        участок = верный or (сегодня if сегодня in УЧАСТКИ else "")
        решение, примечание = спор.get(ключ(имя), ("", ""))
        применено.add(ключ(имя))
        if решение:
            if решение in УЧАСТКИ:
                участок = решение
            else:
                м.уточнить[имя] = примечание or решение

        if not участок:
            м.без_участка.append(имя)
            continue
        м.операции[имя] = участок

    # Приведение не должно СКЛЕИТЬ две разные операции в одну: это
    # было бы хуже несопоставления — вторая молча получила бы участок
    # первой. Проверяется здесь же, на живых данных, а не предполагается.
    склейки: dict = {}
    for имя in м.операции:
        склейки.setdefault(ключ(имя), []).append(имя)
    одинаковые = {k: v for k, v in склейки.items() if len(v) > 1}
    if одинаковые:
        raise ValueError(
            "приведение имён склеило разные операции — правило слишком "
            "грубое:\n  " + "\n  ".join(" | ".join(v) for v in одинаковые.values()))

    # Решение, не нашедшее своей операции, — потерянное решение.
    потеряны = {спор_имена[k]: v[0] for k, v in спор.items()
                if k not in применено and v[0]}
    if потеряны:
        raise РешениеПотеряно(потеряны)
    return м


def загрузить(м: Разметка, db: Path, dry_run: bool = False) -> int:
    if м.без_участка:
        raise СправочникНеполон(м.без_участка)
    if dry_run:
        return 0
    from storage import Storage

    st = Storage(str(db))
    try:
        # Полная замена, а не досыпка: справочник — единая картина, и
        # операция, исчезнувшая из файла технолога, обязана исчезнуть
        # из таблицы. Досыпка оставила бы отменённые привязки жить.
        for имя_участка, code in УЧАСТКИ.items():
            st.delete_area(code)
        for операция, участок in sorted(м.операции.items()):
            st.upsert_area_operation(УЧАСТКИ[участок], участок, операция)
        return len(м.операции)
    finally:
        st.close()


def отчёт(м: Разметка) -> str:
    строки = [f"Готово к загрузке: {м.готово} операций"]
    по_участкам: dict[str, int] = {}
    for у in м.операции.values():
        по_участкам[у] = по_участкам.get(у, 0) + 1
    for у in УЧАСТКИ:
        строки.append(f"   {по_участкам.get(у, 0):4}  {у}")
    if м.исключено:
        строки.append(f"\nНе операции цеха — исключены ({len(м.исключено)}):")
        for имя, почему in м.исключено.items():
            строки.append(f"   {имя} — {почему}")
    if м.уточнить:
        строки.append(f"\nСпорные, решение не принято ({len(м.уточнить)}) — "
                      f"загружены по нынешнему участку, выработка считается "
                      f"с известной погрешностью:")
        for имя, прим in м.уточнить.items():
            строки.append(f"   {имя}{' — ' + прим if прим else ''}")
    if м.без_участка:
        строки.append(f"\nБЕЗ УЧАСТКА ({len(м.без_участка)}) — загрузка "
                      f"невозможна:")
        строки += [f"   {и}" for и in м.без_участка]
    return "\n".join(строки)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--xlsx", required=True, help="файл технолога")
    ap.add_argument("--db", required=True, help="база системы")
    ap.add_argument("--dry-run", action="store_true",
                    help="только показать, что будет загружено")
    args = ap.parse_args()

    м = прочитать(Path(args.xlsx))
    print(отчёт(м))
    try:
        n = загрузить(м, Path(args.db), args.dry_run)
    except СправочникНеполон as e:
        print(f"\nЗАГРУЗКА НЕ ВЫПОЛНЕНА: {e}")
        return 1
    print(f"\n{'Проверка без записи.' if args.dry_run else f'Загружено: {n}'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
